static uint8_t fb[DISP_WIDTH * PAGE_COUNT];

void fb_clear(void) { memset(fb, 0x00, sizeof(fb)); }

void fb_set_pixel(int x, int y, int color) {
    if (x < 0 || x >= DISP_WIDTH || y < 0 || y >= DISP_HEIGHT) return;
    int page = y >> 3;
    int idx = page * DISP_WIDTH + x;
    uint8_t bit = 1 << (y & 0x7);
    if (color) fb[idx] |= bit;
    else fb[idx] &= ~bit;
}

